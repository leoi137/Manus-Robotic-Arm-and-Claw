"""QC gate for a generated dataset: does the data on disk say what it claims?

Two stages, run separately or together.

``raw`` reads ``datasets/raw/<name>/`` — the ledger, the episode files and the
manifest — and checks the things that make a dataset trainable rather than
merely present: every success row has a loadable episode, its arrays agree in
length and stay finite, its timestamps advance at the control rate, its frames
are neither too few, too many, frozen, blank nor blown out, and the manifest's
content hash still recomputes from the episodes it claims to describe.

``lerobot`` re-opens the converted copy in ``datasets/lerobot/<name>/`` and
checks that the conversion moved the data across intact: same episode and frame
counts, and a decoded frame that is still the *same picture* as the raw JPEG at
the same index.

The two stages run under different interpreters. ``raw`` works anywhere with
numpy and Pillow; ``lerobot`` needs the conversion venv:

.. code-block:: bash

    ~/isaaclab-env/bin/python scripts/verify_dataset.py --dataset grasp_cube_dev --stage raw
    ./.venv-lerobot/bin/python scripts/verify_dataset.py --dataset grasp_cube_dev --stage both

The run always prints both numpy versions in play — the one that wrote the
episodes (recorded in the manifest) and the one reading them now. They are
*expected* to differ (2.4.4 vs 2.2.6, see ``docs/PIPELINE.md``) and the
combination is verified interoperable for these dtypes, so this is provenance,
never an assertion: pinning them equal would fail every legitimate cross-venv
run.

Exits non-zero if any check fails, and writes a ``verify_result`` block back
into ``manifest.json`` either way. That block is *not* regenerated by
:func:`manus.recorder.build_manifest`; rebuilding the manifest drops it, which
is intended — a re-derived manifest has not been verified yet.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from collections.abc import Iterable, Sequence
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
# Make the src-layout package importable without installing it.
sys.path.insert(0, str(REPO_ROOT / "src"))

from manus import recorder

VERIFIER_VERSION = 1
"""Bumped whenever a check is added, removed or tightened."""

FRAME_COUNT_RANGE = (30, 600)
"""Plausible episode length, in control steps: shorter is a stub, longer a stall."""

DT_TOLERANCE = 0.20
"""Fractional slack allowed on each inter-frame interval against 1 / control_hz."""

MAX_IDENTICAL_FRAMES = 30
"""Longest run of byte-identical frames tolerated -- a second of a frozen camera."""

FRAME_MEAN_RANGE = (2.0, 253.0)
"""Open interval a frame's mean pixel value must fall in: not black, not blown out."""

MIN_FRAME_STD = 1.0
"""Minimum per-frame pixel standard deviation: a flat frame carries no information."""

MIN_INFORMATIVE_FRACTION = 0.95
"""Fraction of an episode's frames that must satisfy the two statistics above.

Not all of them: the first frames of an episode can legitimately be a
near-uniform close-up of the work surface, and failing an otherwise good
episode over that would train the QC gate to be ignored.
"""

MAX_MEAN_ABS_DIFF = 3.0
"""Tolerance, in 8-bit levels, when matching a converted frame to its raw JPEG.

Exact equality is impossible by construction: the raw frame is already a JPEG,
and lerobot re-encodes those pixels into a video stream (RGB -> YUV, a second
lossy codec, then torchcodec's decode back to RGB). Measured on 320x240
synthetic renders through lerobot 0.6.1's default AV1 encoder: 1.7-2.0 levels
for the *same* frame, 11 levels for a frame five steps away. A 3-level bound
therefore sits well clear of the codec while still catching the failures that
matter -- off-by-one frame indexing, episode reordering, channel swaps,
transposes.
"""

RAW_EPISODE_CHECKS = (
    "episode_loads",
    "array_lengths_agree",
    "arrays_finite",
    "timestamps_monotone",
    "timestep_matches_control_hz",
    "frame_count_in_range",
    "no_stalled_frames",
    "frame_statistics_informative",
)
"""Per-episode raw checks, each reported once with an aggregate detail line."""


@dataclass(frozen=True)
class Check:
    """One reported check: what it was, whether it held, and the evidence."""

    name: str
    passed: bool
    detail: str = ""


class _CheckLog:
    """Collects per-episode failures under a fixed set of check names."""

    def __init__(self, names: Iterable[str]) -> None:
        self._failures: dict[str, list[str]] = {name: [] for name in names}

    def fail(self, name: str, message: str) -> None:
        """Record one episode's failure of check `name`."""
        self._failures[name].append(message)

    def results(self, checked: int) -> list[Check]:
        """One :class:`Check` per name, summarising `checked` episodes."""
        results = []
        for name, failures in self._failures.items():
            if failures:
                detail = f"{len(failures)}/{checked} episodes failed; first: {failures[0]}"
            else:
                detail = f"{checked} episodes"
            results.append(Check(name, not failures, detail))
        return results


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def _longest_identical_run(digests: Sequence[str]) -> int:
    """Length of the longest run of equal consecutive digests."""
    longest = run = 0
    previous = None
    for digest in digests:
        run = run + 1 if digest == previous else 1
        previous = digest
        longest = max(longest, run)
    return longest


# --- Raw stage ---------------------------------------------------------------


def check_raw(dataset_dir: Path, manifest: dict[str, Any]) -> list[Check]:
    """Run every raw-stage check over `dataset_dir`.

    Args:
        dataset_dir: ``datasets/raw/<name>/``.
        manifest: Its manifest, already read.

    Returns:
        One :class:`Check` per check name, per :data:`RAW_EPISODE_CHECKS` plus
        the dataset-level hash check.
    """
    successes = [
        record
        for record in recorder.read_attempts(dataset_dir)
        if record["outcome"] == recorder.SUCCESS
    ]
    log = _CheckLog(RAW_EPISODE_CHECKS)
    print(f"raw: {len(successes)} success rows in {dataset_dir / recorder.LEDGER_NAME}")

    for record in successes:
        label = f"attempt {record['attempt_index']}"
        path = dataset_dir / (record.get("episode_file") or "")
        try:
            episode = recorder.load_episode(path)
        except Exception as error:  # noqa: BLE001 - any failure to load is the finding
            log.fail("episode_loads", f"{label}: {type(error).__name__}: {error}")
            continue
        _check_episode(episode, label, log)

    # An empty dataset passes every per-episode check vacuously, so say so out
    # loud rather than reporting a green run over nothing.
    checks = [Check("ledger_has_successes", bool(successes), f"{len(successes)} success rows")]
    checks += log.results(len(successes))

    # The manifest is a view of the episodes; if it has drifted from them, the
    # dataset_id in every downstream run.json points at data that no longer
    # exists in that form.
    try:
        rebuilt = recorder.build_manifest(dataset_dir, manifest.get("env", {}))
    except Exception as error:  # noqa: BLE001 - report, do not crash the run
        checks.append(Check("dataset_id_recomputes", False, f"{type(error).__name__}: {error}"))
    else:
        matches = rebuilt["dataset_id"] == manifest.get("dataset_id")
        checks.append(
            Check(
                "dataset_id_recomputes",
                matches,
                f"{rebuilt['dataset_id'][:12]} from disk vs "
                f"{str(manifest.get('dataset_id'))[:12]} in the manifest",
            )
        )
        counts_match = rebuilt["counts"] == manifest.get("counts")
        checks.append(
            Check(
                "manifest_counts_match",
                counts_match,
                f"{rebuilt['counts']} from disk vs {manifest.get('counts')} in the manifest",
            )
        )
    return checks


def _check_episode(episode: recorder.Episode, label: str, log: _CheckLog) -> None:
    """Run the per-episode raw checks, recording failures into `log`."""
    steps = len(episode)
    lengths = {
        "frames": steps,
        "joint_pos": len(episode.joint_pos),
        "actions": len(episode.actions),
        "timestamps": len(episode.timestamps),
    }
    if len(set(lengths.values())) != 1:
        # Everything below indexes the arrays together; without alignment the
        # remaining findings would be noise generated by this one.
        log.fail("array_lengths_agree", f"{label}: {lengths}")
        return

    for name in ("joint_pos", "actions", "timestamps"):
        array = getattr(episode, name)
        if not np.isfinite(array).all():
            log.fail("arrays_finite", f"{label}: {name} holds non-finite values")

    deltas = np.diff(episode.timestamps)
    if deltas.size and deltas.min() <= 0.0:
        index = int(np.argmin(deltas))
        log.fail(
            "timestamps_monotone",
            f"{label}: dt {deltas[index]:+.6f}s at step {index + 1} does not advance",
        )
    expected_dt = 1.0 / float(episode.meta.get("control_hz", recorder.CONTROL_HZ))
    if deltas.size:
        worst = int(np.argmax(np.abs(deltas - expected_dt)))
        if abs(deltas[worst] - expected_dt) > DT_TOLERANCE * expected_dt:
            log.fail(
                "timestep_matches_control_hz",
                f"{label}: dt {deltas[worst]:.6f}s at step {worst + 1}, "
                f"expected {expected_dt:.6f}s +/-{DT_TOLERANCE:.0%}",
            )

    if not FRAME_COUNT_RANGE[0] <= steps <= FRAME_COUNT_RANGE[1]:
        log.fail("frame_count_in_range", f"{label}: {steps} frames, want {FRAME_COUNT_RANGE}")

    # One decode pass feeds both pixel checks: decoding is the expensive part of
    # this script and there is no reason to pay for it twice.
    digests, informative = [], 0
    for index in range(steps):
        frame = episode.frame(index)
        digests.append(hashlib.sha256(frame.tobytes()).hexdigest())
        mean, deviation = float(frame.mean()), float(frame.std())
        if FRAME_MEAN_RANGE[0] < mean < FRAME_MEAN_RANGE[1] and deviation > MIN_FRAME_STD:
            informative += 1

    stalled = _longest_identical_run(digests)
    if stalled > MAX_IDENTICAL_FRAMES:
        log.fail("no_stalled_frames", f"{label}: {stalled} identical frames in a row")
    if steps and informative < MIN_INFORMATIVE_FRACTION * steps:
        log.fail(
            "frame_statistics_informative",
            f"{label}: {informative}/{steps} frames inside "
            f"mean {FRAME_MEAN_RANGE}, std > {MIN_FRAME_STD}",
        )


# --- LeRobot stage -----------------------------------------------------------


def _as_uint8_hwc(image: Any) -> np.ndarray:
    """Normalise a lerobot image item to a (height, width, 3) uint8 array.

    LeRobotDataset hands back a torch tensor in channel-first order, float32 in
    [0, 1] unless the dataset was opened with ``return_uint8=True``.
    """
    array = image.numpy() if hasattr(image, "numpy") else np.asarray(image)
    if array.ndim != 3:
        raise ValueError(f"expected a 3-D image, got shape {array.shape}")
    if array.shape[0] == 3 and array.shape[2] != 3:
        array = array.transpose(1, 2, 0)
    if np.issubdtype(array.dtype, np.floating):
        array = np.rint(np.clip(array, 0.0, 1.0) * 255.0)
    return array.astype(np.uint8)


def _episode_start(dataset: Any, episode_index: int) -> int:
    """Global frame index at which `episode_index` starts."""
    episodes = getattr(dataset.meta, "episodes", None)
    if episodes is not None:
        try:
            return int(episodes[episode_index]["dataset_from_index"])
        except (KeyError, IndexError, TypeError):
            pass
    if episode_index == 0:
        return 0
    raise ValueError(f"cannot locate the start of episode {episode_index} in this dataset")


def check_lerobot(
    dataset_dir: Path,
    lerobot_dir: Path,
    manifest: dict[str, Any],
    repo_id: str,
    image_key: str | None,
    episode_ordinal: int,
) -> list[Check]:
    """Check the converted dataset against the raw one it was built from.

    Args:
        dataset_dir: ``datasets/raw/<name>/``.
        lerobot_dir: ``datasets/lerobot/<name>/``.
        manifest: The raw manifest.
        repo_id: Identifier to open the local dataset under; with a local
            ``root`` it is only a label.
        image_key: Camera feature to compare, or None to use the only one.
        episode_ordinal: Which episode to pixel-compare — the n-th success in
            ledger order, which the converter writes as lerobot episode n.

    Returns:
        The checks, all failed-with-reason rather than raised where the
        conversion itself is at fault.
    """
    from lerobot.datasets.lerobot_dataset import LeRobotDataset

    checks = []
    try:
        dataset = LeRobotDataset(repo_id, root=lerobot_dir)
    except Exception as error:  # noqa: BLE001 - an unloadable dataset is the finding
        return [Check("lerobot_dataset_loads", False, f"{type(error).__name__}: {error}")]
    # Repo-relative: this detail lands in the tracked manifest, and an absolute
    # path would bake the generating machine's home directory into it.
    try:
        loaded_from = Path(lerobot_dir).resolve().relative_to(REPO_ROOT)
    except ValueError:
        loaded_from = Path(lerobot_dir)
    checks.append(Check("lerobot_dataset_loads", True, f"{loaded_from} as {repo_id!r}"))

    counts = manifest.get("counts") or {}
    episodes_match = int(dataset.num_episodes) == counts.get("successes")
    checks.append(
        Check(
            "lerobot_episode_count_matches",
            episodes_match,
            f"{dataset.num_episodes} episodes vs {counts.get('successes')} successes",
        )
    )
    frames_match = int(dataset.num_frames) == counts.get("frames")
    checks.append(
        Check(
            "lerobot_frame_count_matches",
            frames_match,
            f"{dataset.num_frames} frames vs {counts.get('frames')} recorded",
        )
    )

    try:
        checks.append(
            _check_frame_matches_raw(dataset, dataset_dir, image_key, episode_ordinal)
        )
    except Exception as error:  # noqa: BLE001 - report, do not crash the run
        checks.append(
            Check("lerobot_frame_matches_raw", False, f"{type(error).__name__}: {error}")
        )
    return checks


def _check_frame_matches_raw(
    dataset: Any, dataset_dir: Path, image_key: str | None, episode_ordinal: int
) -> Check:
    """Compare one converted frame with the raw JPEG at the same index."""
    if image_key is None:
        cameras = list(dataset.meta.camera_keys)
        if len(cameras) != 1:
            raise ValueError(f"pass --image-key: this dataset has cameras {cameras}")
        image_key = cameras[0]

    successes = [
        record
        for record in recorder.read_attempts(dataset_dir)
        if record["outcome"] == recorder.SUCCESS
    ]
    record = successes[episode_ordinal]
    episode = recorder.load_episode(dataset_dir / record["episode_file"])
    # The middle frame: the wrist is mid-descent there, so the picture is
    # specific to its index in a way frame 0 (arm at reset) is not.
    frame_index = len(episode) // 2

    item = dataset[_episode_start(dataset, episode_ordinal) + frame_index]
    located = (int(item["episode_index"]), int(item["frame_index"]))
    if located != (episode_ordinal, frame_index):
        raise ValueError(
            f"landed on episode/frame {located}, wanted {(episode_ordinal, frame_index)}"
        )

    converted = _as_uint8_hwc(item[image_key])
    raw = episode.frame(frame_index)
    if converted.shape != raw.shape:
        raise ValueError(f"shape {converted.shape} from lerobot vs {raw.shape} raw")
    difference = float(np.abs(converted.astype(np.int16) - raw.astype(np.int16)).mean())
    return Check(
        "lerobot_frame_matches_raw",
        difference < MAX_MEAN_ABS_DIFF,
        f"attempt {record['attempt_index']} frame {frame_index} ({image_key}): "
        f"mean abs diff {difference:.2f}, tolerance {MAX_MEAN_ABS_DIFF}",
    )


# --- Entry point -------------------------------------------------------------


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--dataset", required=True, help="dataset name, e.g. grasp_cube_dev")
    parser.add_argument(
        "--stage", choices=("raw", "lerobot", "both"), default="raw", help="which stage to check"
    )
    parser.add_argument(
        "--root", type=Path, default=REPO_ROOT, help="repository root holding datasets/"
    )
    parser.add_argument(
        "--repo-id", default=None, help="lerobot repo id (default manus/<dataset>)"
    )
    parser.add_argument("--image-key", default=None, help="camera feature to pixel-compare")
    parser.add_argument(
        "--episode-ordinal",
        type=int,
        default=0,
        help="which converted episode to pixel-compare (default the first)",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    """Verify one dataset. Returns the process exit code."""
    args = _parse_args(argv)
    dataset_dir = args.root / "datasets" / "raw" / args.dataset
    lerobot_dir = args.root / "datasets" / "lerobot" / args.dataset

    if not dataset_dir.is_dir():
        raise SystemExit(f"no such dataset: {dataset_dir}")
    try:
        manifest = recorder.read_manifest(dataset_dir)
    except FileNotFoundError:
        raise SystemExit(
            f"{dataset_dir / recorder.MANIFEST_NAME} is missing -- generate it with "
            "manus.recorder.build_manifest() before verifying"
        ) from None

    if args.stage in ("lerobot", "both"):
        # Fail before doing the expensive raw pass, not after.
        try:
            import lerobot  # noqa: F401
        except ImportError as error:
            raise SystemExit(
                f"--stage {args.stage} needs lerobot ({error}). Run this stage with the "
                f"conversion venv:\n  ./.venv-lerobot/bin/python "
                f"{Path(__file__).resolve().relative_to(REPO_ROOT)} "
                f"--dataset {args.dataset} --stage {args.stage}"
            ) from None
        if not lerobot_dir.is_dir():
            raise SystemExit(f"no converted dataset at {lerobot_dir} -- run convert_dataset.py")

    # Provenance, never an assertion: the writer and the reader are expected to
    # disagree here (see the module docstring).
    numpy_versions = {
        "running": np.__version__,
        "recorded": (manifest.get("env") or {}).get("numpy"),
    }
    print(
        f"numpy: {numpy_versions['running']} reading, "
        f"{numpy_versions['recorded'] or 'unrecorded'} wrote the episodes"
    )

    checks: list[Check] = []
    if args.stage in ("raw", "both"):
        checks += check_raw(dataset_dir, manifest)
    if args.stage in ("lerobot", "both"):
        checks += check_lerobot(
            dataset_dir,
            lerobot_dir,
            manifest,
            args.repo_id or f"manus/{args.dataset}",
            args.image_key,
            args.episode_ordinal,
        )

    for check in checks:
        print(f"{'PASS' if check.passed else 'FAIL'}: {check.name} -- {check.detail}")

    passed = all(check.passed for check in checks)
    manifest["verify_result"] = {
        "verifier_version": VERIFIER_VERSION,
        "stage": args.stage,
        "passed": passed,
        "checked_at": _utc_now(),
        "numpy": numpy_versions,
        "checks": [asdict(check) for check in checks],
    }
    recorder.write_manifest(dataset_dir, manifest)

    failed = [check.name for check in checks if not check.passed]
    print(
        f"{'PASS' if passed else 'FAIL'}: {args.dataset} stage={args.stage}, "
        f"{len(checks) - len(failed)}/{len(checks)} checks passed"
        + (f" (failed: {', '.join(failed)})" if failed else "")
    )
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
